-- 3501 3502 3503 are the "after" phases (no client phase, server side only) for the copies that would stand on a stage:
--   3501 Shrine of Goldrinn once 25272 (Horde) or 25273 (Alliance) is rewarded; 3502 Gates of Sothann once 25608 is
--   rewarded; 3503 the west (Regrowth, Scorched Plain camp) once 25372 is rewarded.
